from __future__ import annotations

from datetime import date, datetime
from typing import List, Optional

from sqlalchemy import (
    REAL,
    BigInteger,
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    FetchedValue,
    ForeignKey,
    Index,
    Integer,
    Text,
    false,
    func,
)
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


class Base(DeclarativeBase):
    pass


class Source(Base):
    __tablename__ = "source"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    title: Mapped[str] = mapped_column(Text, nullable=False)
    filename: Mapped[str] = mapped_column(Text, nullable=False)
    doc_date: Mapped[Optional[date]] = mapped_column(Date, nullable=True)
    author: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    uploaded_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    chunks: Mapped[List["Chunk"]] = relationship(
        back_populates="source",
        cascade="all, delete-orphan",
        order_by="Chunk.position",
    )


class Chunk(Base):
    __tablename__ = "chunk"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    source_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("source.id", ondelete="CASCADE"), nullable=False
    )
    position: Mapped[int] = mapped_column(Integer, nullable=False)
    text: Mapped[str] = mapped_column(Text, nullable=False)

    # Generated by Postgres (GENERATED ALWAYS AS ... STORED), so it is never
    # written by the application. Deferred: only loaded when accessed.
    tsv: Mapped[str] = mapped_column(
        TSVECTOR, nullable=False, server_default=FetchedValue(), deferred=True
    )

    source: Mapped["Source"] = relationship(back_populates="chunks")

    __table_args__ = (
        Index("ix_chunk_tsv", "tsv", postgresql_using="gin"),
        Index("ix_chunk_source_id_position", "source_id", "position"),
    )


class Run(Base):
    __tablename__ = "run"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    question: Mapped[str] = mapped_column(Text, nullable=False)
    status: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    finished_at: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    error: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    demo: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=false()
    )

    claims: Mapped[List["Claim"]] = relationship(
        back_populates="run", cascade="all, delete-orphan", order_by="Claim.id"
    )


class Claim(Base):
    __tablename__ = "claim"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    run_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("run.id", ondelete="CASCADE"), nullable=False
    )
    text: Mapped[str] = mapped_column(Text, nullable=False)
    claim_date: Mapped[Optional[date]] = mapped_column(Date, nullable=True)
    owner: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    status: Mapped[str] = mapped_column(Text, nullable=False)
    confidence: Mapped[float] = mapped_column(REAL, nullable=False)
    uncertainty_note: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    run: Mapped["Run"] = relationship(back_populates="claims")
    evidence: Mapped[List["Evidence"]] = relationship(
        back_populates="claim", cascade="all, delete-orphan", order_by="Evidence.id"
    )

    __table_args__ = (
        CheckConstraint(
            "status IN ('verified', 'conflict', 'uncertain', 'superseded')",
            name="ck_claim_status",
        ),
    )


class Evidence(Base):
    __tablename__ = "evidence"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    claim_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("claim.id", ondelete="CASCADE"), nullable=False
    )
    chunk_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("chunk.id", ondelete="CASCADE"), nullable=False
    )
    quote: Mapped[str] = mapped_column(Text, nullable=False)
    role: Mapped[str] = mapped_column(Text, nullable=False)

    claim: Mapped["Claim"] = relationship(back_populates="evidence")

    __table_args__ = (
        CheckConstraint("role IN ('supports', 'contradicts')", name="ck_evidence_role"),
    )


class Conflict(Base):
    __tablename__ = "conflict"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    run_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("run.id", ondelete="CASCADE"), nullable=False
    )
    claim_a_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("claim.id", ondelete="CASCADE"), nullable=False
    )
    claim_b_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("claim.id", ondelete="CASCADE"), nullable=False
    )
    reason: Mapped[str] = mapped_column(Text, nullable=False)


class Supersession(Base):
    __tablename__ = "supersession"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    run_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("run.id", ondelete="CASCADE"), nullable=False
    )
    old_claim_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("claim.id", ondelete="CASCADE"), nullable=False
    )
    new_claim_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("claim.id", ondelete="CASCADE"), nullable=False
    )
    reason: Mapped[str] = mapped_column(Text, nullable=False)
